import csv
from collections import Counter

print("\n" + "=" * 60)
print("       PRODUCT REQUIREMENTS DOCUMENT GENERATOR")
print("=" * 60)

# Read customer feedback
with open("customer_feedback.csv", "r", encoding="utf-8") as file:
    reviews = list(csv.DictReader(file))

# Product problem categories
categories = {
    "Performance": ["slow", "crashes", "loading", "errors"],
    "User Experience": ["confusing", "navigation", "find", "steps"],
    "Customer Support": ["support", "respond", "resolved"],
    "Pricing": ["expensive", "pricing", "price"],
    "Product Features": ["feature", "dashboard", "analytics", "track"]
}

solutions = {
    "Performance": "Optimise application speed, improve system stability and reduce crashes.",
    "User Experience": "Simplify navigation and streamline the customer journey.",
    "Customer Support": "Improve support response workflows and issue resolution.",
    "Pricing": "Review pricing structure and improve communication of product value.",
    "Product Features": "Improve existing functionality and introduce customer-requested features."
}

kpis = {
    "Performance": ["Page load time", "Application crash rate"],
    "User Experience": ["Task completion rate", "Checkout conversion rate"],
    "Customer Support": ["First response time", "Customer satisfaction score"],
    "Pricing": ["Customer retention rate", "Plan conversion rate"],
    "Product Features": ["Feature adoption rate", "Monthly active users"]
}

# Identify feedback by category
matched_feedback = Counter()
evidence = {}

for category, keywords in categories.items():
    matches = []

    for review in reviews:
        text = review["feedback"].lower()

        if any(word in text for word in keywords):
            matches.append(review["feedback"])

    matched_feedback[category] = len(matches)
    evidence[category] = matches

# Select the most frequently mentioned problem
selected_category = matched_feedback.most_common(1)[0][0]

print(f"\nSelected product problem: {selected_category}")
print(f"Customer mentions: {matched_feedback[selected_category]}")

solution = solutions[selected_category]
success_metrics = kpis[selected_category]

# Create PRD
prd = f"""
# PRODUCT REQUIREMENTS DOCUMENT

## 1. Product Overview

Product Area: {selected_category}

Document Type: Initial Product Requirements Document

## 2. Problem Statement

Customers have reported recurring issues related to {selected_category.lower()}.

These problems may negatively affect customer satisfaction,
product usability and business performance.

## 3. Customer Evidence

Total matching customer feedback:
{matched_feedback[selected_category]}

"""

for item in evidence[selected_category]:
    prd += f"\n- {item}"

prd += f"""

## 4. Proposed Solution

{solution}

## 5. Business Objectives

- Improve customer satisfaction.
- Reduce recurring customer complaints.
- Improve product usability and reliability.
- Support long-term customer retention.

## 6. User Stories

### User Story 1

As a customer, I want an improved {selected_category.lower()} experience
so that I can use the product more effectively.

Acceptance Criteria:

- The improvement addresses the identified customer problem.
- The experience is tested across relevant user journeys.
- No critical regression issues are introduced.

### User Story 2

As a product manager, I want to monitor improvements
so that I can measure their business impact.

Acceptance Criteria:

- Relevant product KPIs are tracked.
- Performance can be compared before and after implementation.
- Results are available for product review.

## 7. Success Metrics

"""

for metric in success_metrics:
    prd += f"\n- {metric}"

prd += """

## 8. Risks and Considerations

- Proposed improvements require technical feasibility assessment.
- Changes should be validated through user testing.
- Customer data should be handled responsibly.
- Success metrics require baseline measurements.

## 9. Next Steps

1. Validate the problem with additional customer research.
2. Discuss feasibility with engineering stakeholders.
3. Prioritise the proposed solution.
4. Define implementation milestones.
5. Measure results after release.

---

Generated by AI Product Intelligence Agent.
Note: This is a prototype-generated draft requiring
product manager and stakeholder validation.
"""

# Save document automatically
with open("product_requirements_document.md", "w", encoding="utf-8") as file:
    file.write(prd)

print("\n" + "=" * 60)
print("PRD GENERATED SUCCESSFULLY!")
print("=" * 60)

print("\nProduct Area:", selected_category)
print("\nProposed Solution:", solution)

print("\nUser Stories: 2")
print("Success Metrics:", ", ".join(success_metrics))

print("\nSaved file: product_requirements_document.md")
print("=" * 60)
